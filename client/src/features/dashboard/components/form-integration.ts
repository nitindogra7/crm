export type FormCodeLanguage = "curl" | "fetch" | "html" | "react" | "python" | "node";

export function getFormSnippet(language: FormCodeLanguage, endpoint: string): string {
  const url = JSON.stringify(endpoint);
  switch (language) {
    case "html": return [
      '<form action=' + url + ' method="POST">',
      '  <label>Name <input name="name" required /></label>',
      '  <label>Email <input name="email" type="email" required /></label>',
      '  <label>Message <textarea name="message" required></textarea></label>',
      '  <input name="_gotcha" hidden tabindex="-1" autocomplete="off" />',
      '  <button type="submit">Send message</button>',
      '</form>',
    ].join("\n");
    case "curl": return [
      'curl --request POST ' + url + ' \\',
      '  --header "Content-Type: application/json" \\',
      '  --header "x-api-key: $INFRALY_API_KEY" \\',
      '  --data \'{"name":"Alex Rivera","email":"alex@example.com","message":"Hello"}\'',
    ].join("\n");
    case "fetch": return [
      '// Server route: keep INFRALY_API_KEY on your server.',
      'export async function POST(request: Request) {',
      '  const body = await request.json();',
      '  const response = await fetch(' + url + ', {',
      '    method: "POST",',
      '    headers: {',
      '      "Content-Type": "application/json",',
      '      "x-api-key": process.env.INFRALY_API_KEY!,',
      '    },',
      '    body: JSON.stringify(body),',
      '    signal: AbortSignal.timeout(15000),',
      '  });',
      '  const result = await response.json();',
      '  return Response.json(result, { status: response.status });',
      '}',
    ].join("\n");
    case "react": return [
      '\"use client\";',
      'import { useState, type FormEvent } from "react";',
      '',
      'export function ContactForm() {',
      '  const [sending, setSending] = useState(false);',
      '  const [message, setMessage] = useState("");',
      '  async function submit(event: FormEvent<HTMLFormElement>) {',
      '    event.preventDefault();',
      '    if (sending) return;',
      '    const values = new FormData(event.currentTarget);',
      '    setSending(true);',
      '    try {',
      '      const response = await fetch(' + url + ', {',
      '        method: "POST",',
      '        headers: { "Content-Type": "application/json" },',
      '        body: JSON.stringify(Object.fromEntries(values)),',
      '        signal: AbortSignal.timeout(15000),',
      '      });',
      '      const result = await response.json();',
      '      if (result.status === "quarantined") {',
      '        setMessage("Received for review.");',
      '      } else if (response.ok && result.status === "success") {',
      '        setMessage("Message sent.");',
      '      } else {',
      '        throw new Error(result.message || result.error || "Please try again.");',
      '      }',
      '    } catch { setMessage("Could not send. Please try again."); }',
      '    finally { setSending(false); }',
      '  }',
      '  return <form onSubmit={submit}>',
      '    <label>Name <input name="name" required /></label>',
      '    <label>Email <input name="email" type="email" required /></label>',
      '    <label>Message <textarea name="message" required /></label>',
      '    <input name="_gotcha" hidden tabIndex={-1} autoComplete="off" />',
      '    <button disabled={sending}>{sending ? "Sending..." : "Send"}</button>',
      '    <p role="status">{message}</p>',
      '  </form>;',
      '}',
    ].join("\n");
    case "node": return [
      'app.post("/api/contact", async (req, res) => {',
      '  try {',
      '    const response = await fetch(' + url + ', {',
      '      method: "POST",',
      '      headers: {',
      '        "Content-Type": "application/json",',
      '        "x-api-key": process.env.INFRALY_API_KEY,',
      '      },',
      '      body: JSON.stringify(req.body),',
      '      signal: AbortSignal.timeout(15000),',
      '    });',
      '    res.status(response.status).json(await response.json());',
      '  } catch { res.status(502).json({ error: "Could not send submission" }); }',
      '});',
    ].join("\n");
    case "python": return [
      'import os',
      'import requests',
      '',
      'response = requests.post(',
      '    ' + url + ',',
      '    headers={"x-api-key": os.environ["INFRALY_API_KEY"]},',
      '    json={"name": "Alex Rivera", "email": "alex@example.com", "message": "Hello"},',
      '    timeout=15,',
      ')',
      'print(response.status_code, response.json())',
    ].join("\n");
  }
}
