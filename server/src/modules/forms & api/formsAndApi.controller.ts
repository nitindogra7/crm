// Compatibility facade; routes import domain controllers directly.
import { formsAndApiService, FormsAndApiService } from "./formsAndApi.services";
import { DashboardsController } from "../dashboards/dashboards.controller";
import { FormsController } from "../forms/forms.controller";
import { ApiKeysController } from "../api-keys/api-keys.controller";
import { IngestionController } from "../ingestion/ingestion.controller";
import { LegacyLeadsController } from "../leads/legacy-leads.controller";
import { SpamController } from "../spam/spam.controller";
import { StatsController } from "../stats/stats.controller";
export class FormsAndApiController {
  getDashboards: DashboardsController["getDashboards"];
  createDashboard: DashboardsController["createDashboard"];
  updateDashboard: DashboardsController["updateDashboard"];
  getForms: FormsController["getForms"];
  getFormById: FormsController["getFormById"];
  createForm: FormsController["createForm"];
  updateForm: FormsController["updateForm"];
  deleteForm: FormsController["deleteForm"];
  getApiKeys: ApiKeysController["getApiKeys"];
  createApiKey: ApiKeysController["createApiKey"];
  regenerateApiKey: ApiKeysController["regenerateApiKey"];
  revokeApiKey: ApiKeysController["revokeApiKey"];
  submitForm: IngestionController["submitForm"];
  simulateSubmission: LegacyLeadsController["simulateSubmission"];
  getLeads: LegacyLeadsController["getLeads"];
  deleteLead: LegacyLeadsController["deleteLead"];
  batchDeleteLeads: LegacyLeadsController["batchDeleteLeads"];
  batchUpdateLeadStatus: LegacyLeadsController["batchUpdateLeadStatus"];
  updateLeadStatus: LegacyLeadsController["updateLeadStatus"];
  getSpam: SpamController["getSpam"];
  rescueSpam: SpamController["rescueSpam"];
  getStats: StatsController["getStats"];
  constructor(service: FormsAndApiService = formsAndApiService) {
    const dashboards = new DashboardsController(service);
    this.getDashboards = dashboards.getDashboards;
    this.createDashboard = dashboards.createDashboard;
    this.updateDashboard = dashboards.updateDashboard;
    const forms = new FormsController(service);
    this.getForms = forms.getForms;
    this.getFormById = forms.getFormById;
    this.createForm = forms.createForm;
    this.updateForm = forms.updateForm;
    this.deleteForm = forms.deleteForm;
    const apikeys = new ApiKeysController(service);
    this.getApiKeys = apikeys.getApiKeys;
    this.createApiKey = apikeys.createApiKey;
    this.regenerateApiKey = apikeys.regenerateApiKey;
    this.revokeApiKey = apikeys.revokeApiKey;
    const ingestion = new IngestionController(service);
    this.submitForm = ingestion.submitForm;
    const legacyleads = new LegacyLeadsController(service);
    this.simulateSubmission = legacyleads.simulateSubmission;
    this.getLeads = legacyleads.getLeads;
    this.deleteLead = legacyleads.deleteLead;
    this.batchDeleteLeads = legacyleads.batchDeleteLeads;
    this.batchUpdateLeadStatus = legacyleads.batchUpdateLeadStatus;
    this.updateLeadStatus = legacyleads.updateLeadStatus;
    const spam = new SpamController(service);
    this.getSpam = spam.getSpam;
    this.rescueSpam = spam.rescueSpam;
    const stats = new StatsController(service);
    this.getStats = stats.getStats;
  }
}
export const formsAndApiController = new FormsAndApiController();
