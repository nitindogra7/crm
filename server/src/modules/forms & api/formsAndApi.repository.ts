// Compatibility facade. Queries live in the owning domain modules.
import { DashboardsRepository } from "../dashboards/dashboards.repository";
import { FormsRepository } from "../forms/forms.repository";
import { ApiKeysRepository } from "../api-keys/api-keys.repository";
import { LegacyLeadsRepository } from "../leads/legacy-leads.repository";
import { SpamRepository } from "../spam/spam.repository";
import { StatsRepository } from "../stats/stats.repository";
export class FormsAndApiRepository {
  createDashboard: DashboardsRepository["createDashboard"];
  findDashboardsByUserId: DashboardsRepository["findDashboardsByUserId"];
  findDashboardById: DashboardsRepository["findDashboardById"];
  findDashboardBySlug: DashboardsRepository["findDashboardBySlug"];
  updateDashboard: DashboardsRepository["updateDashboard"];
  createForm: FormsRepository["createForm"];
  findFormsByDashboardId: FormsRepository["findFormsByDashboardId"];
  findFormById: FormsRepository["findFormById"];
  findFormByDashboardAndSlug: FormsRepository["findFormByDashboardAndSlug"];
  findFormByGlobalSlug: FormsRepository["findFormByGlobalSlug"];
  updateForm: FormsRepository["updateForm"];
  deleteForm: FormsRepository["deleteForm"];
  incrementLeadCount: FormsRepository["incrementLeadCount"];
  incrementSpamCount: FormsRepository["incrementSpamCount"];
  decrementSpamCount: FormsRepository["decrementSpamCount"];
  decrementLeadCount: FormsRepository["decrementLeadCount"];
  createApiKey: ApiKeysRepository["createApiKey"];
  findApiKeysByDashboardId: ApiKeysRepository["findApiKeysByDashboardId"];
  findApiKeyByKey: ApiKeysRepository["findApiKeyByKey"];
  revokeApiKey: ApiKeysRepository["revokeApiKey"];
  revokeAllActiveKeysForDashboard: ApiKeysRepository["revokeAllActiveKeysForDashboard"];
  touchApiKeyLastUsed: ApiKeysRepository["touchApiKeyLastUsed"];
  createLead: LegacyLeadsRepository["createLead"];
  findLeadsByDashboardId: LegacyLeadsRepository["findLeadsByDashboardId"];
  findLeadById: LegacyLeadsRepository["findLeadById"];
  updateLeadStatus: LegacyLeadsRepository["updateLeadStatus"];
  deleteLead: LegacyLeadsRepository["deleteLead"];
  deleteLeads: LegacyLeadsRepository["deleteLeads"];
  batchUpdateLeadStatus: LegacyLeadsRepository["batchUpdateLeadStatus"];
  findLeadsWithPagination: LegacyLeadsRepository["findLeadsWithPagination"];
  createSpam: SpamRepository["createSpam"];
  findSpamByDashboardId: SpamRepository["findSpamByDashboardId"];
  findSpamById: SpamRepository["findSpamById"];
  deleteSpam: SpamRepository["deleteSpam"];
  getStats: StatsRepository["getStats"];
  constructor() {
    const dashboards = new DashboardsRepository();
    this.createDashboard = dashboards.createDashboard.bind(dashboards);
    this.findDashboardsByUserId = dashboards.findDashboardsByUserId.bind(dashboards);
    this.findDashboardById = dashboards.findDashboardById.bind(dashboards);
    this.findDashboardBySlug = dashboards.findDashboardBySlug.bind(dashboards);
    this.updateDashboard = dashboards.updateDashboard.bind(dashboards);
    const forms = new FormsRepository();
    this.createForm = forms.createForm.bind(forms);
    this.findFormsByDashboardId = forms.findFormsByDashboardId.bind(forms);
    this.findFormById = forms.findFormById.bind(forms);
    this.findFormByDashboardAndSlug = forms.findFormByDashboardAndSlug.bind(forms);
    this.findFormByGlobalSlug = forms.findFormByGlobalSlug.bind(forms);
    this.updateForm = forms.updateForm.bind(forms);
    this.deleteForm = forms.deleteForm.bind(forms);
    this.incrementLeadCount = forms.incrementLeadCount.bind(forms);
    this.incrementSpamCount = forms.incrementSpamCount.bind(forms);
    this.decrementSpamCount = forms.decrementSpamCount.bind(forms);
    this.decrementLeadCount = forms.decrementLeadCount.bind(forms);
    const apikeys = new ApiKeysRepository();
    this.createApiKey = apikeys.createApiKey.bind(apikeys);
    this.findApiKeysByDashboardId = apikeys.findApiKeysByDashboardId.bind(apikeys);
    this.findApiKeyByKey = apikeys.findApiKeyByKey.bind(apikeys);
    this.revokeApiKey = apikeys.revokeApiKey.bind(apikeys);
    this.revokeAllActiveKeysForDashboard = apikeys.revokeAllActiveKeysForDashboard.bind(apikeys);
    this.touchApiKeyLastUsed = apikeys.touchApiKeyLastUsed.bind(apikeys);
    const legacyleads = new LegacyLeadsRepository();
    this.createLead = legacyleads.createLead.bind(legacyleads);
    this.findLeadsByDashboardId = legacyleads.findLeadsByDashboardId.bind(legacyleads);
    this.findLeadById = legacyleads.findLeadById.bind(legacyleads);
    this.updateLeadStatus = legacyleads.updateLeadStatus.bind(legacyleads);
    this.deleteLead = legacyleads.deleteLead.bind(legacyleads);
    this.deleteLeads = legacyleads.deleteLeads.bind(legacyleads);
    this.batchUpdateLeadStatus = legacyleads.batchUpdateLeadStatus.bind(legacyleads);
    this.findLeadsWithPagination = legacyleads.findLeadsWithPagination.bind(legacyleads);
    const spam = new SpamRepository();
    this.createSpam = spam.createSpam.bind(spam);
    this.findSpamByDashboardId = spam.findSpamByDashboardId.bind(spam);
    this.findSpamById = spam.findSpamById.bind(spam);
    this.deleteSpam = spam.deleteSpam.bind(spam);
    const stats = new StatsRepository();
    this.getStats = stats.getStats.bind(stats);
  }
}
export const formsAndApiRepository = new FormsAndApiRepository();
