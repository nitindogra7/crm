// Compatibility facade for existing integrations and injected repositories.
import { formsAndApiRepository, FormsAndApiRepository } from "./formsAndApi.repository";
import { DashboardsService } from "../dashboards/dashboards.services";
import { FormsService } from "../forms/forms.services";
import { ApiKeysService } from "../api-keys/api-keys.services";
import { IngestionService } from "../ingestion/ingestion.services";
import { LegacyLeadsService } from "../leads/legacy-leads.services";
import { SpamService } from "../spam/spam.services";
import { StatsService } from "../stats/stats.services";
export class FormsAndApiService {
  getOrCreateDashboards: DashboardsService["getOrCreateDashboards"];
  createDashboard: DashboardsService["createDashboard"];
  getDashboardById: DashboardsService["getDashboardById"];
  updateDashboard: DashboardsService["updateDashboard"];
  createForm: FormsService["createForm"];
  getForms: FormsService["getForms"];
  getFormById: FormsService["getFormById"];
  updateForm: FormsService["updateForm"];
  deleteForm: FormsService["deleteForm"];
  getApiKeys: ApiKeysService["getApiKeys"];
  generateApiKey: ApiKeysService["generateApiKey"];
  regenerateApiKey: ApiKeysService["regenerateApiKey"];
  revokeApiKey: ApiKeysService["revokeApiKey"];
  ingestSubmission: IngestionService["ingestSubmission"];
  simulateLead: LegacyLeadsService["simulateLead"];
  getLeads: LegacyLeadsService["getLeads"];
  getAllLeads: LegacyLeadsService["getAllLeads"];
  updateLeadStatus: LegacyLeadsService["updateLeadStatus"];
  deleteLead: LegacyLeadsService["deleteLead"];
  batchDeleteLeads: LegacyLeadsService["batchDeleteLeads"];
  batchUpdateLeadStatus: LegacyLeadsService["batchUpdateLeadStatus"];
  getSpam: SpamService["getSpam"];
  rescueSpamLead: SpamService["rescueSpamLead"];
  getStats: StatsService["getStats"];
  constructor(repository: FormsAndApiRepository = formsAndApiRepository) {
    const dashboards = new DashboardsService(repository);
    this.getOrCreateDashboards = dashboards.getOrCreateDashboards.bind(dashboards);
    this.createDashboard = dashboards.createDashboard.bind(dashboards);
    this.getDashboardById = dashboards.getDashboardById.bind(dashboards);
    this.updateDashboard = dashboards.updateDashboard.bind(dashboards);
    const forms = new FormsService(repository, new DashboardsService(repository));
    this.createForm = forms.createForm.bind(forms);
    this.getForms = forms.getForms.bind(forms);
    this.getFormById = forms.getFormById.bind(forms);
    this.updateForm = forms.updateForm.bind(forms);
    this.deleteForm = forms.deleteForm.bind(forms);
    const apikeys = new ApiKeysService(repository, new DashboardsService(repository));
    this.getApiKeys = apikeys.getApiKeys.bind(apikeys);
    this.generateApiKey = apikeys.generateApiKey.bind(apikeys);
    this.regenerateApiKey = apikeys.regenerateApiKey.bind(apikeys);
    this.revokeApiKey = apikeys.revokeApiKey.bind(apikeys);
    const ingestion = new IngestionService(repository);
    this.ingestSubmission = ingestion.ingestSubmission.bind(ingestion);
    const legacyleads = new LegacyLeadsService(repository, new DashboardsService(repository));
    this.simulateLead = legacyleads.simulateLead.bind(legacyleads);
    this.getLeads = legacyleads.getLeads.bind(legacyleads);
    this.getAllLeads = legacyleads.getAllLeads.bind(legacyleads);
    this.updateLeadStatus = legacyleads.updateLeadStatus.bind(legacyleads);
    this.deleteLead = legacyleads.deleteLead.bind(legacyleads);
    this.batchDeleteLeads = legacyleads.batchDeleteLeads.bind(legacyleads);
    this.batchUpdateLeadStatus = legacyleads.batchUpdateLeadStatus.bind(legacyleads);
    const spam = new SpamService(repository, new DashboardsService(repository));
    this.getSpam = spam.getSpam.bind(spam);
    this.rescueSpamLead = spam.rescueSpamLead.bind(spam);
    const stats = new StatsService(repository, new DashboardsService(repository));
    this.getStats = stats.getStats.bind(stats);
  }
}
export const formsAndApiService = new FormsAndApiService();
